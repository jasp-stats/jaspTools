test_that("the plot review includes new SVGs and their structure for the selected analysis", {
  module <- withr::local_tempdir()
  testDir <- file.path(module, "tests", "testthat")
  snapDir <- file.path(testDir, "_snaps")
  writeSnapshotText("test_that('Example results match', {})", file.path(testDir, "test-other-Example Data.R"))
  for (context in c("other-Example Data", "Unrelated"))
    writeSnapshotText("<svg/>", file.path(snapDir, context, "fit.new.svg"))
  pending <- file.path(snapDir, "other-Example Data", "reference_plotobject", "fit.new.rds")
  dir.create(dirname(pending))
  saveRDS(list(size = 2), pending)
  writeSnapshotText("Pending HTML", file.path(snapDir, "other-Example Data", "notice.new.html"))
  local_mocked_bindings(getModulePathFromRFunction = function(name) module)

  reports <- manageTestPlots("Example", open = FALSE)
  expect_named(reports, basename(module))
  withr::defer(unlink(reports[[1L]]))
  html <- snapshotText(reports[[1L]])
  expect_true(grepl("other-Example Data/fit.svg", html, fixed = TRUE))
  expect_true(grepl(snapshotFileHash(pending), html, fixed = TRUE))
  expect_false(grepl("Unrelated/fit.svg", html, fixed = TRUE))
  expect_false(grepl("notice.html", html, fixed = TRUE))
})
